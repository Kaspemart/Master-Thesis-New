"""
Generate all 9 base SV datasets (train / validation / test) × (T=500 / 1000 / 2000).

Dataset plan (do not change seeds):

    Split       N        T     Seed  File
    -------------------------------------------------------
    test        200      500   42    data/test_T500.npz
    test        200      1000  42    data/test_T1000.npz
    test        200      2000  42    data/test_T2000.npz
    train       90,000   500   123   data/train_T500.npz
    train       90,000   1000  456   data/train_T1000.npz
    train       90,000   2000  789   data/train_T2000.npz
    validation  10,000   500   321   data/val_T500.npz
    validation  10,000   1000  654   data/val_T1000.npz
    validation  10,000   2000  987   data/val_T2000.npz

All series are drawn from the base SV model only.
Leverage training data will be generated separately when needed.

TEST SET NESTING:
    The three test datasets share seed=42 and are generated by simulating at T=2000 once,
    then slicing: test_T500 = first 500 steps, test_T1000 = first 1000 steps.
    This guarantees that the only variable across sample sizes is T — the underlying
    parameter draws, noise realisations, and latent paths are identical up to each cutoff.
    This is a methodological strength that must be described explicitly in the thesis.

    Why not simulate independently at each T?
    The simulator pre-draws eps (T×N) then eta (T×N) in two separate blocks. For T=500,
    eta[t=0] comes from RNG draw 100,001; for T=1000, eta[t=0] comes from draw 200,001.
    So independent simulations at different T values with the same seed produce different
    latent paths despite sharing parameter values. Slicing from T=2000 avoids this.

Usage:
    uv run python scripts/generate_datasets.py
    uv run python scripts/generate_datasets.py --dry-run   # print plan, do not generate
    uv run python scripts/generate_datasets.py --skip-existing  # skip already-generated files
"""

import argparse
import sys
import time
from dataclasses import dataclass
from pathlib import Path

import numpy as np

# Allow running from repo root without installing the package
sys.path.insert(0, str(Path(__file__).parent.parent))

from src.simulation.simulator import SimulationResult, simulate_sv, save_dataset


@dataclass
class DatasetSpec:
    split: str
    N: int
    T: int
    seed: int
    path: Path


# Train and validation datasets: each generated independently at its own T.
# Test datasets: generated by simulating at T=2000 and slicing (see nesting note above).
TRAIN_VAL_DATASETS = [
    DatasetSpec("train",   90_000,    500, 123,  Path("data/train_T500.npz")),
    DatasetSpec("train",   90_000,   1000, 456,  Path("data/train_T1000.npz")),
    DatasetSpec("train",   90_000,   2000, 789,  Path("data/train_T2000.npz")),
    DatasetSpec("val",     10_000,    500, 321,  Path("data/val_T500.npz")),
    DatasetSpec("val",     10_000,   1000, 654,  Path("data/val_T1000.npz")),
    DatasetSpec("val",     10_000,   2000, 987,  Path("data/val_T2000.npz")),
]

TEST_SEED = 42
TEST_N = 200
TEST_T_MAX = 2000
TEST_SLICES = [
    (500,  Path("data/test_T500.npz")),
    (1000, Path("data/test_T1000.npz")),
    (2000, Path("data/test_T2000.npz")),
]

ALL_PATHS = (
    [s.path for s in TRAIN_VAL_DATASETS]
    + [path for _, path in TEST_SLICES]
)


def format_size(path: Path) -> str:
    mb = path.stat().st_size / 1_048_576
    return f"{mb:.1f} MB"


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate base SV datasets.")
    parser.add_argument("--dry-run", action="store_true",
                        help="Print the generation plan without writing any files.")
    parser.add_argument("--skip-existing", action="store_true",
                        help="Skip datasets whose output file already exists.")
    args = parser.parse_args()

    repo_root = Path(__file__).parent.parent

    print("Dataset generation plan:")
    print(f"{'Split':<12} {'N':>8} {'T':>6} {'Seed':>6}  {'File'}")
    print("-" * 60)
    for T, path in TEST_SLICES:
        print(f"{'test':<12} {TEST_N:>8,} {T:>6} {TEST_SEED:>6}  {path}  [sliced from T=2000]")
    for spec in TRAIN_VAL_DATASETS:
        print(f"{spec.split:<12} {spec.N:>8,} {spec.T:>6} {spec.seed:>6}  {spec.path}")
    print()

    if args.dry_run:
        print("Dry run — no files written.")
        return

    total_start = time.time()
    idx = 1
    total = len(TEST_SLICES) + len(TRAIN_VAL_DATASETS)

    # --- Test datasets (nested by slicing from T=2000) ---
    test_paths_needed = [
        path for _, path in TEST_SLICES
        if not (args.skip_existing and (repo_root / path).exists())
    ]
    if test_paths_needed:
        print(f"[{idx}/{total}–{idx+len(TEST_SLICES)-1}/{total}] "
              f"Simulating test N={TEST_N} T={TEST_T_MAX} seed={TEST_SEED} ...",
              end=" ", flush=True)
        t0 = time.time()
        full = simulate_sv(N=TEST_N, T=TEST_T_MAX, seed=TEST_SEED)
        elapsed = time.time() - t0
        print(f"done in {elapsed:.1f}s")

        for T, path in TEST_SLICES:
            out_path = repo_root / path
            if args.skip_existing and out_path.exists():
                print(f"  Skipping {path} (already exists, {format_size(out_path)})")
            else:
                sliced = SimulationResult(
                    returns=full.returns[:, :T],
                    params=full.params,
                    latent_h=full.latent_h[:, :T],
                )
                save_dataset(out_path, sliced)
                print(f"  Saved {path}  →  {format_size(out_path)}")
    else:
        for T, path in TEST_SLICES:
            print(f"[{idx}/{total}] Skipping {path} (already exists, {format_size(repo_root / path)})")
            idx += 1

    idx += len(TEST_SLICES)

    # --- Train and validation datasets ---
    for spec in TRAIN_VAL_DATASETS:
        out_path = repo_root / spec.path

        if args.skip_existing and out_path.exists():
            print(f"[{idx}/{total}] Skipping {spec.path} (already exists, {format_size(out_path)})")
            idx += 1
            continue

        print(f"[{idx}/{total}] Generating {spec.split} T={spec.T} N={spec.N:,} seed={spec.seed} ...",
              end=" ", flush=True)
        t0 = time.time()
        result = simulate_sv(N=spec.N, T=spec.T, seed=spec.seed)
        save_dataset(out_path, result)
        elapsed = time.time() - t0
        print(f"done in {elapsed:.1f}s  →  {format_size(out_path)}")
        idx += 1

    total_elapsed = time.time() - total_start
    print(f"\nAll datasets generated in {total_elapsed:.1f}s")
    print(f"Output directory: {repo_root / 'data'}")


if __name__ == "__main__":
    main()
