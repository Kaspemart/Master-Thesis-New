"""
Assemble ALL Chapter 6 (misspecification) results into one consolidated file,
computed directly from the source result files so it always matches.

Writes:
  experiments/chapter6_consolidated_results.json   — machine-readable, exact
  experiments/chapter6_results.md                  — human-readable reference

Run:  uv run python scripts/assemble_chapter6_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

R = Path("results/misspec")
NAMES = {
    "asv":  ["mu", "phi", "sigma_eta", "rho"],
    "svt":  ["mu", "phi", "sigma_eta", "nu"],
    "asvt": ["mu", "phi", "sigma_eta", "rho", "nu"],
}


def metrics(est, true, names):
    err = est - true
    out = {}
    for i, nm in enumerate(names):
        out[nm] = dict(rmse=float(np.sqrt((err[:, i] ** 2).mean())),
                       bias=float(err[:, i].mean()))
    return out


def nu_split(est, true, names):
    if "nu" not in names:
        return None
    j = names.index("nu"); tn = true[:, j]
    res = {}
    for lo, hi in [(0, 10), (10, 100)]:
        m = (tn >= lo) & (tn < hi)
        if m.sum():
            res[f"nu_{lo}_{hi}"] = dict(
                n=int(m.sum()),
                rmse=float(np.sqrt(((est[m, j] - tn[m]) ** 2).mean())),
                bias=float((est[m, j] - tn[m]).mean()))
    return res


def tstat(x):
    x = np.asarray(x)
    se = x.std(ddof=1) / np.sqrt(len(x))
    return float(x.mean()), float(x.mean() / se)


def main():
    out = {"_note": "Chapter 6 misspecification results, assembled from "
                    "results/misspec/*.npz. T=1000, N=200, seed 999. OOS = "
                    "out-of-sample predictive log-lik (window [1000,2000]), "
                    "particle filter 10k particles, 3 matched seeds.",
           "parameter_estimates": {}, "predictive_ll": {}}

    # --- parameter estimates: 4 cells per scenario ---
    cell_files = {"a_misspec_NN": "{s}_tcn", "b_misspec_MCMC": "{s}_stochvol",
                  "c_correct_NN": "{s}_tcn_correct", "d_correct_MCMC": "{s}_stochvol_correct"}
    for scen, names in NAMES.items():
        out["parameter_estimates"][scen] = {}
        base_names = ["mu", "phi", "sigma_eta"]
        for cell, tmpl in cell_files.items():
            d = np.load(R / f"{tmpl.format(s=scen)}.npz")
            est, true = d["est"], d["true"]
            # misspecified cells only estimate 3 base params
            nm = base_names if est.shape[1] == 3 else names
            entry = dict(metrics=metrics(est, true[:, :est.shape[1]], nm))
            sp = nu_split(est, true, nm)
            if sp:
                entry["nu_split"] = sp
            if "rhat" in d:
                entry["frac_rhat_gt_1p1"] = {
                    n: float((d["rhat"][:, i] > 1.1).mean()) for i, n in enumerate(nm)}
            out["parameter_estimates"][scen][cell] = entry

    # --- predictive log-likelihood 2x2: out-of-sample, in-sample, cleaned ---
    for scen in NAMES:
        ab = np.load(R / f"{scen}_predictive_ll.npz")
        cd = np.load(R / f"{scen}_predictive_ll_correct.npz")
        a, b, c, d = ab["tcn_oos"], ab["sv_oos"], cd["c_oos"], cd["d_oos"]
        m_ca, t_ca = tstat(c - a)
        m_db, t_db = tstat(d - b)
        m_cd, t_cd = tstat(c - d)
        m_ab, t_ab = tstat(a - b)  # central a vs b
        ai, bi, ci, di = ab["tcn_in"], ab["sv_in"], cd["c_in"], cd["d_in"]
        m_ab_in, t_ab_in = tstat(ai - bi)
        # non-convergence-cleaned c-d (cell d converged on every param)
        rhat = np.load(R / f"{scen}_stochvol_correct.npz")["rhat"]
        conv = (rhat <= 1.1).all(axis=1)
        m_cd_cl, t_cd_cl = tstat((c - d)[conv])
        out["predictive_ll"][scen] = dict(
            oos_mean=dict(a=float(a.mean()), b=float(b.mean()),
                          c=float(c.mean()), d=float(d.mean())),
            insample_mean=dict(a=float(ai.mean()), b=float(bi.mean()),
                               c=float(ci.mean()), d=float(di.mean())),
            contrasts=dict(
                a_minus_b=dict(mean=m_ab, t=t_ab),
                a_minus_b_insample=dict(mean=m_ab_in, t=t_ab_in),
                c_minus_a=dict(mean=m_ca, t=t_ca),
                d_minus_b=dict(mean=m_db, t=t_db),
                c_minus_d=dict(mean=m_cd, t=t_cd),
                c_minus_d_cleaned=dict(mean=m_cd_cl, t=t_cd_cl,
                                       n_kept=int(conv.sum()))))

    Path("experiments").mkdir(exist_ok=True)
    with open("experiments/chapter6_consolidated_results.json", "w") as f:
        json.dump(out, f, indent=2)

    # --- human-readable markdown ---
    L = ["# Chapter 6 — Misspecification Results (consolidated reference)",
         "",
         "T=1000, N=200, seed 999. Generated by `assemble_chapter6_results.py` "
         "from `results/misspec/*.npz`.", "",
         "## Out-of-sample predictive log-likelihood (2×2, higher = better)", "",
         "| Scenario | (a) misspec NN | (b) misspec MCMC | (c) correct NN | (d) correct MCMC |",
         "|---|---|---|---|---|"]
    for scen in NAMES:
        o = out["predictive_ll"][scen]["oos_mean"]
        L.append(f"| {scen} | {o['a']:.2f} | {o['b']:.2f} | {o['c']:.2f} | {o['d']:.2f} |")
    L += ["", "### Contrasts (mean, paired t-stat)", "",
          "| Scenario | a−b (central) | c−a (NN gain) | d−b (MCMC gain) | c−d (NN vs MCMC) |",
          "|---|---|---|---|---|"]
    for scen in NAMES:
        ct = out["predictive_ll"][scen]["contrasts"]
        L.append(f"| {scen} | {ct['a_minus_b']['mean']:+.2f} (t{ct['a_minus_b']['t']:.1f}) "
                 f"| {ct['c_minus_a']['mean']:+.2f} (t{ct['c_minus_a']['t']:.1f}) "
                 f"| {ct['d_minus_b']['mean']:+.2f} (t{ct['d_minus_b']['t']:.1f}) "
                 f"| {ct['c_minus_d']['mean']:+.2f} (t{ct['c_minus_d']['t']:.1f}) |")
    # in-sample table
    L += ["", "## In-sample predictive log-likelihood (2×2)", "",
          "| Scenario | (a) misspec NN | (b) misspec MCMC | (c) correct NN | (d) correct MCMC |",
          "|---|---|---|---|---|"]
    for scen in NAMES:
        o = out["predictive_ll"][scen]["insample_mean"]
        L.append(f"| {scen} | {o['a']:.2f} | {o['b']:.2f} | {o['c']:.2f} | {o['d']:.2f} |")
    # convergence-cleaned c-d
    L += ["", "## Non-convergence-cleaned c−d (OOS predictive LL)",
          "Cell (d) converged on every parameter (R-hat ≤ 1.1); NN always converges.", "",
          "| Scenario | c−d full | c−d cleaned | series kept |",
          "|---|---|---|---|"]
    for scen in NAMES:
        ct = out["predictive_ll"][scen]["contrasts"]
        L.append(f"| {scen} | {ct['c_minus_d']['mean']:+.2f} (t{ct['c_minus_d']['t']:.1f}) "
                 f"| {ct['c_minus_d_cleaned']['mean']:+.2f} (t{ct['c_minus_d_cleaned']['t']:.1f}) "
                 f"| {ct['c_minus_d_cleaned']['n_kept']}/200 |")
    # parameter RMSE and bias by cell
    L += ["", "## Parameter RMSE and bias by cell", ""]
    for scen, names in NAMES.items():
        L += [f"### {scen}", "",
              "| Cell | metric | " + " | ".join(names) + " |",
              "|---|---|" + "|".join(["---"] * len(names)) + "|"]
        for cell in ["a_misspec_NN", "b_misspec_MCMC", "c_correct_NN", "d_correct_MCMC"]:
            met = out["parameter_estimates"][scen][cell]["metrics"]
            rr = [f"{met[n]['rmse']:.4f}" if n in met else "—" for n in names]
            bb = [f"{met[n]['bias']:+.4f}" if n in met else "—" for n in names]
            L.append(f"| {cell} | RMSE | " + " | ".join(rr) + " |")
            L.append(f"| | bias | " + " | ".join(bb) + " |")
        L.append("")
    Path("experiments/chapter6_results.md").write_text("\n".join(L))

    print("Wrote experiments/chapter6_consolidated_results.json")
    print("Wrote experiments/chapter6_results.md")
    print("\n".join(L[:16]))


if __name__ == "__main__":
    main()
